window.getProductById = function (id) {
  return (window.TECHHIVE_PRODUCTS || []).find((product) => product.id === id) || null;
};

window.formatPrice = function (value) {
  if (value === undefined || value === null || value === "") return "KSh 0";
  return `KSh ${Number(value).toLocaleString("en-KE")}`;
};

window.stockClass = function (status) {
  const normalized = (status || "").toLowerCase().replace(/\s+/g, "-");
  if (normalized.includes("available")) return "available";
  if (normalized.includes("few")) return "few-remaining";
  if (normalized.includes("out") || normalized.includes("confirm")) return normalized.includes("confirm") ? "needs-confirmation" : "out-of-stock";
  return "needs-confirmation";
};

window.renderProductCard = function (product) {
  const badges = [];
  if (product.touchscreen) badges.push("Touchscreen");
  if (product.x360) badges.push("X360");
  if (product.deal) badges.push("Price Drop");

  const meta = [
    product.ram && product.ram !== "" ? product.ram : null,
    product.storage && product.storage !== "" ? product.storage : null,
    product.processor && product.processor !== "" ? product.processor : null
  ].filter(Boolean);

  return `
    <article class="product-card" data-product-id="${product.id}">
      <div class="product-media">
        <img src="${product.image || "https://images.unsplash.com/photo-1496181133206-80ce9b88a853?auto=format&fit=crop&w=900&q=80"}" alt="${product.brand} ${product.name}" loading="lazy" />
        <div class="product-badges">
          ${badges.map((badge) => `<span class="product-badge ${badge === "Price Drop" ? "warning" : ""}">${badge}</span>`).join("")}
        </div>
      </div>
      <div class="product-body">
        <div class="product-brand">${product.brand}</div>
        <h3 class="product-name">${product.name}</h3>
        <div class="key-spec">${product.processor && product.processor !== "" ? product.processor : "Not specified"}${product.generation && product.generation !== "" ? ` • ${product.generation}` : ""}</div>
        <div class="product-meta">
          ${meta.map((item) => `<span>${item}</span>`).join("")}
        </div>
        <div class="price-row">
          <div class="price-wrap">
            <span class="current-price">${window.formatPrice(product.price)}</span>
          </div>
          <span class="stock-status ${window.stockClass(product.stockStatus)}">${product.stockStatus || "Needs confirmation"}</span>
        </div>
        <div class="product-actions">
          <a href="product.html?id=${product.id}" class="small-button">View Details</a>
          <button class="small-button" type="button" data-add-to-cart="${product.id}">Add to Cart</button>
          <button class="small-button" type="button" data-whatsapp-product="${product.id}">WhatsApp</button>
        </div>
        <button class="icon-button" type="button" data-compare-id="${product.id}">Compare</button>
      </div>
    </article>
  `;
};

window.whatsAppProductMessage = function (product) {
  const parts = [
    "Hello Ann, I am interested in this laptop:",
    `Product: ${product.name}`,
    `Price: ${window.formatPrice(product.price)}`,
    `RAM: ${product.ram || "Not specified"}`,
    `Storage: ${product.storage || "Not specified"}`,
    "Is it currently available?"
  ];
  return parts.join("\n");
};

window.whatsAppCartMessage = function (items) {
  const lines = ["Hello Ann, I would like to order:"];
  items.forEach((item, index) => {
    lines.push(`${index + 1}. ${item.name}`);
    lines.push(`   ${window.formatPrice(item.price)}`);
  });
  const total = items.reduce((sum, item) => sum + item.price * item.quantity, 0);
  lines.push("");
  lines.push(`Estimated total: ${window.formatPrice(total)}`);
  lines.push("Please confirm availability and delivery/pickup options.");
  return lines.join("\n");
};

